import { cmsPageResponse, cmsRedirectResponse, cmsSitemapResponse } from "./_cms-runtime.js";
import { isTelegramPath, telegramPathResponse, maybeNotifyTelegramRelease } from "./_telegram-support.js";
import { RELEASE_DISPATCH_PATH, handleReleaseDispatch } from "./_telegram-release-journal.js";

// OutPOSt Pages Worker
// Hotfix v0.24.5.3 — public-question proxy header allowlist.
// Reconstructed source: only /api/public-question is proxied;
// all other requests continue through env.ASSETS.fetch(request).

const PUBLIC_QUESTION_PATH = "/api/public-question";
const CUSTOMER_PORTAL_ORIGIN = "https://cabinet.outpost.com.ua";
const INSTALLER_PATH_PATTERN = /^\/downloads\/OutPOSt-Setup-v([^/]+)\.exe$/i;
const TELEGRAM_RELEASE_CHECK_PATHS = new Set(["/", "/download", "/download.html"]);
const CANONICAL_PUBLIC_HOSTS = new Set(["outpost.com.ua", "www.outpost.com.ua"]);

function productionIntegrationsAllowed(url, env) {
  return url.protocol === "https:" && !url.port &&
    CANONICAL_PUBLIC_HOSTS.has(url.hostname.toLowerCase()) &&
    String(env.OUTPOST_PREVIEW_ONLY || "") !== "1";
}

function previewIntegrationResponse(health = false) {
  return new Response(JSON.stringify(health
    ? { ok: true, enabled: false, environment: "preview", integrations_disabled: true }
    : { ok: false, error: "preview_integration_disabled", message: "У тестовому середовищі надсилання звернень і Telegram вимкнено." }), {
    status: health ? 200 : 403,
    headers: {
      "Content-Type": "application/json; charset=utf-8",
      "Cache-Control": "no-store",
      "X-Robots-Tag": "noindex, nofollow",
      "X-Content-Type-Options": "nosniff"
    }
  });
}

// Pages advanced-mode _worker.js owns the response. Cloudflare _headers alone
// does not reliably apply Cache-Control to responses generated by this Worker.
// Restrict no-cache to the five versioned browser-only demo resources.
const DEMO_RUNTIME_ASSETS = new Set([
  "/assets/outpost-demo-v1.css",
  "/assets/outpost-demo-v1.js",
  "/assets/outpost-demo-modules-v1.js",
  "/assets/outpost-demo-returns-v1.js",
  "/assets/outpost-demo-products-v1.js"
]);

function protectDemoAssetFreshness(request, response) {
  if (request.method !== "GET" && request.method !== "HEAD") return response;
  const pathname = new URL(request.url).pathname;
  if (!DEMO_RUNTIME_ASSETS.has(pathname) || response.status !== 200) return response;

  // env.ASSETS response headers may be immutable: copy the full response.
  const headers = new Headers(response.headers);
  headers.set("Cache-Control", "no-cache, max-age=0, must-revalidate");
  return new Response(request.method === "HEAD" ? null : response.body, {
    status: response.status,
    statusText: response.statusText,
    headers
  });
}


function publicQuestionTarget(requestUrl) {
  const incoming = new URL(requestUrl);
  const target = new URL(PUBLIC_QUESTION_PATH, CUSTOMER_PORTAL_ORIGIN);
  target.search = incoming.search;
  return target;
}

function buildProxyHeaders(request) {
  const headers = new Headers();

  // Only forward headers the public-question backend actually needs.
  // Do NOT clone the entire incoming Cloudflare request header set:
  // Workers Request construction rejects/controls several cf- / proxy headers.
  const accept = request.headers.get("accept");
  if (accept) headers.set("accept", accept);

  const contentType = request.headers.get("content-type");
  if (contentType) headers.set("content-type", contentType);

  // Customer Portal accepts public questions only from the canonical public site origin.
  headers.set("origin", "https://outpost.com.ua");

  // Preserve the original visitor IP for the backend's rate-limit logic
  // using our own application header, not Cloudflare's protected headers.
  const clientIp = request.headers.get("cf-connecting-ip");
  if (clientIp) headers.set("x-outpost-client-ip", clientIp);

  return headers;
}

async function proxyPublicQuestion(request) {
  const target = publicQuestionTarget(request.url);

  const init = {
    method: request.method,
    headers: buildProxyHeaders(request),
    redirect: "manual"
  };

  if (request.method !== "GET" && request.method !== "HEAD") {
    init.body = request.body;
  }

  return fetch(target.toString(), init);
}

function protectStaticPreviewIndexability(request, response, env = {}) {
  const url = new URL(request.url);
  if (productionIntegrationsAllowed(url, env)) return response;

  const contentType = (response.headers.get("content-type") || "").toLowerCase();
  const isHtml = contentType.includes("text/html");
  const isSitemap = url.pathname === "/sitemap.xml";

  if (!isHtml && !isSitemap) return response;

  const headers = new Headers(response.headers);
  headers.set("X-Robots-Tag", "noindex, nofollow");
  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers
  });
}

function installerDownloadVersion(request) {
  if (request.method !== "GET" || request.headers.has("range")) return null;
  const match = new URL(request.url).pathname.match(INSTALLER_PATH_PATTERN);
  return match ? match[1] : null;
}

async function recordInstallerDownload(env, version) {
  if (!env.ANALYTICS_DB) return;

  const now = new Date().toISOString();
  const dayUtc = now.slice(0, 10);
  await env.ANALYTICS_DB.prepare(`
    INSERT INTO installer_download_daily
      (day_utc, version, request_count, first_seen_at, last_seen_at)
    VALUES (?, ?, 1, ?, ?)
    ON CONFLICT(day_utc, version) DO UPDATE SET
      request_count = request_count + 1,
      last_seen_at = excluded.last_seen_at
  `).bind(dayUtc, version, now, now).run();
}

export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    const integrationsAllowed = productionIntegrationsAllowed(url, env);

    // Preview must not send real enquiries, change a Telegram webhook, notify
    // subscribers or count downloads in an accidentally copied production DB.
    if (!integrationsAllowed && (
      url.pathname === PUBLIC_QUESTION_PATH || url.pathname.startsWith("/api/telegram/")
    )) {
      return previewIntegrationResponse(url.pathname === "/api/telegram/health" && request.method === "GET");
    }

    if (url.pathname === RELEASE_DISPATCH_PATH) return handleReleaseDispatch(request, env);

    if (isTelegramPath(url.pathname)) {
      return telegramPathResponse(request, env);
    }

    if (url.pathname === PUBLIC_QUESTION_PATH) {
      return proxyPublicQuestion(request);
    }

    // Release notifications are isolated, read the official current version from
    // the static download page and run in the background. They never change the
    // response path for the public site, CMS, cabinet proxy or installer download.
    if (
      integrationsAllowed &&
      request.method === "GET" &&
      TELEGRAM_RELEASE_CHECK_PATHS.has(url.pathname) &&
      env.ANALYTICS_DB &&
      env.TELEGRAM_BOT_TOKEN &&
      String(env.TELEGRAM_PUBLIC_ENABLED || "") === "1"
      && String(env.TELEGRAM_CONFIRMED_RELEASES_ENABLED || "") !== "1"
    ) {
      ctx.waitUntil(
        maybeNotifyTelegramRelease(env).catch((error) => {
          console.error(JSON.stringify({ event: "telegram_release_check_failed", name: error?.name || "Error" }));
        })
      );
    }

    if (env.CMS_DB) {
      try {
        const redirect = await cmsRedirectResponse(request, env);
        if (redirect) return redirect;
        const cmsPage = await cmsPageResponse(request, env);
        if (cmsPage) return protectStaticPreviewIndexability(request, cmsPage, env);
      } catch (error) {
        console.error(JSON.stringify({event:"cms_public_fallback",path:url.pathname,error:error?.name||"Error"}));
      }
    }

    let response = await env.ASSETS.fetch(request);
    if (url.pathname === "/sitemap.xml" && env.CMS_DB) {
      try { response = await cmsSitemapResponse(request, env, response) || response; }
      catch (error) { console.error(JSON.stringify({event:"cms_sitemap_fallback",error:error?.name||"Error"})); }
    }
    const version = installerDownloadVersion(request);

    // Count only successful initial installer requests. Range requests are excluded
    // so one resumed/segmented download cannot inflate the aggregate.
    if (integrationsAllowed && version && response.status === 200 && env.ANALYTICS_DB) {
      ctx.waitUntil(
        recordInstallerDownload(env, version).catch((error) => {
          console.error("Unable to record installer download", error);
        })
      );
    }

    response = protectDemoAssetFreshness(request, response);
    response = protectStaticPreviewIndexability(request, response, env);
    return response;
  }
};
